#!/usr/bin/env python3
"""Write password.js for the optional shared password.

Reads the BOOK_PASSWORD environment variable (from the repo secret of the
same name). If it's set, stores its SHA-256 hash in password.js so the
site asks for it; if not, leaves password.js empty (no password).
Runs only in the GitHub build; the filled-in file is never committed.
"""
import hashlib
import os
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
password = os.environ.get("BOOK_PASSWORD", "")
digest = hashlib.sha256(password.encode("utf-8")).hexdigest() if password else ""
(ROOT / "password.js").write_text(
    "// Generated by the publish workflow. Do not commit.\n"
    f'export const PASSWORD_SHA256 = "{digest}";\n',
    encoding="utf-8",
)
print("password: on" if password else "password: off")
summary = os.environ.get("GITHUB_STEP_SUMMARY")
if summary:
    with open(summary, "a", encoding="utf-8") as f:
        f.write("Password: **on** (readers can type any username)\n" if password
                else "Password: **off** (anyone with the link can read)\n")
